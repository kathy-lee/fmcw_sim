"""Write vectors.h: the input samples for the FFT comparison, as C source.

The board has no filesystem, so whatever the harness transforms has to be
compiled into the image. Each FFT in the comparison reads the same integers
from this header.

The radar vectors are one simulated chirp, quantized the way convert_q15.c
quantizes an ADC frame: a 12-bit signed grid spanning +/- adc_full_scale,
left-aligned by 3 into int16. The 32-point vector is the first 32 samples of
the 128-sample chirp, quantized with the same full scale, so the short vector
is an exact prefix of the long one.

The constant vectors make scaling errors obvious: the Q15 transform with its
1/n scaling gives exactly 1000 in bin 0 and exactly zero elsewhere, so one
halving too many or too few is a factor of two in bin 0.

Usage:  python gen_vectors.py [--scenario ...] [--self-check]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from scripts.export_for_c import ADC_HEADROOM
from simulator.beat_signal_generator import FMCWBeatSignalGenerator, load_scenario

DC_VALUE = 1000
ADC_BITS = 12
ALIGN_SHIFT = 3
CODE_MAX = (1 << (ADC_BITS - 1)) - 1      # 2047
CODE_MIN = -(1 << (ADC_BITS - 1))         # -2048
SCENARIO = "scenarios/scenario_mimo_stream_128.json"
N_LONG = 128
N_SHORT = 32
OUT = Path(__file__).resolve().parent / "vectors.h"


def quantize(x: np.ndarray, full_scale: float) -> np.ndarray:
    """One component onto the 12-bit grid, then left-aligned into int16.

    Rounding is half away from zero, matching C's lround, not NumPy's
    half-to-even. The clip test is written against the rounding boundary so
    the decision happens before the rounding, as it does in C.
    """
    r = x * ((1 << (ADC_BITS - 1)) / full_scale)
    q = np.trunc(r + np.copysign(0.5, r))
    q = np.clip(q, CODE_MIN, CODE_MAX)
    return (q.astype(np.int32) << ALIGN_SHIFT).astype(np.int16)


def radar_vector(scenario: str) -> np.ndarray:
    """The first N_LONG samples of chirp 0, quantized once."""
    cfg, targets = load_scenario(str(ROOT / scenario))
    gen = FMCWBeatSignalGenerator(cfg)
    frame = gen.generate_frame_mimo(targets, frame_index=0)
    seg = np.asarray(frame[0, 0, :N_LONG])
    if len(seg) != N_LONG:
        raise SystemExit(f"scenario has {len(seg)} samples per chirp, wanted {N_LONG}")
    peak = max(float(np.max(np.abs(seg.real))), float(np.max(np.abs(seg.imag))))
    full_scale = peak * ADC_HEADROOM if peak > 0.0 else 1.0
    out = np.empty(N_LONG, dtype=[("re", np.int16), ("im", np.int16)])
    out["re"] = quantize(seg.real, full_scale)
    out["im"] = quantize(seg.imag, full_scale)
    return out


def dc_vector(n: int) -> np.ndarray:
    out = np.zeros(n, dtype=[("re", np.int16), ("im", np.int16)])
    out["re"] = DC_VALUE
    return out


def fmt(name: str, size: str, v: np.ndarray) -> str:
    rows = ",\n".join(
        "    {%6d, %6d}" % (int(s["re"]), int(s["im"])) for s in v)
    return f"static const vec_sample {name}[{size}] = {{\n{rows}\n}};\n"


def render(radar: np.ndarray, scenario: str) -> str:
    return f"""/* Generated by gen_vectors.py from {scenario} -- do not edit. */
#ifndef VECTORS_H
#define VECTORS_H
#include <stdint.h>

#define VEC_N_128 {N_LONG}
#define VEC_N_32 {N_SHORT}

typedef struct {{ int16_t re, im; }} vec_sample;

{fmt("vec_dc_128", "VEC_N_128", dc_vector(N_LONG))}
{fmt("vec_radar_128", "VEC_N_128", radar)}
{fmt("vec_dc_32", "VEC_N_32", dc_vector(N_SHORT))}
{fmt("vec_radar_32", "VEC_N_32", radar[:N_SHORT])}
#endif
"""


def self_check(radar: np.ndarray, dc: np.ndarray, n: int) -> None:
    """Properties that must hold, checkable without a reference transform.

    Every quantized value is a multiple of 8, because it is a 12-bit code
    shifted left by 3: evidence that the alignment was applied exactly once.
    """
    assert len(radar) == n and len(dc) == n, "wrong vector length"
    for f in ("re", "im"):
        assert np.all(radar[f] % 8 == 0), f"radar {f} not left-aligned by 3"
        lim = CODE_MAX << ALIGN_SHIFT
        assert np.all(np.abs(radar[f].astype(np.int32)) <= lim), \
            f"radar {f} outside the 12-bit grid"
    assert np.all(dc["re"] == DC_VALUE) and np.all(dc["im"] == 0), "dc corrupt"
    assert np.any(radar["re"] != 0), "radar vector is all zero"
    print(f"self-check passed: {n} samples, "
          f"peak |re| {int(np.max(np.abs(radar['re'])))}, "
          f"peak |im| {int(np.max(np.abs(radar['im'])))}")


def main() -> None:
    ap = argparse.ArgumentParser(description="Emit vectors.h for the CMSIS-DSP FFT comparison.")
    ap.add_argument("--scenario", default=SCENARIO)
    ap.add_argument("--self-check", action="store_true")
    args = ap.parse_args()

    radar = radar_vector(args.scenario)

    if args.self_check:
        self_check(radar, dc_vector(N_LONG), N_LONG)
        self_check(radar[:N_SHORT], dc_vector(N_SHORT), N_SHORT)
    OUT.write_text(render(radar, args.scenario))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
