"""Write vectors.h — the input samples, as C source.

The board has no filesystem, so nothing can be loaded at run time the way
c_frontend/tests/vectors/*.bin are: whatever the harness transforms has to
be compiled into the image. That makes a header the delivery format for
data. ref_host.c includes this same header, which is what guarantees the
board and the host start from byte-identical integers rather than from two
files that could drift apart.

The radar vector is one chirp from the simulator, quantized the way
convert_q15.c quantizes an ADC frame: a 12-bit signed grid spanning
+/- adc_full_scale, left-aligned by 3 into int16. That replica does not have
to be faithful to be useful — the device and the host consume the same
integers from this header, so quantization sits upstream of everything the
comparison claims. It only has to produce realistic values.

The constant vector earns its flash: its transform is exactly 1000 in bin
0 and exactly zero elsewhere, which pins the per-stage halvings to exactly
1/n. One shift too many or too few and bin 0 is off by a factor of two,
visible at a glance in a serial capture on a board with no debugger
attached.

The AVR shim is kept even though this target does not need it: on
Cortex-M a const table lands in flash without an attribute, and the shim
falls through to plain indexing on every non-AVR target.

Usage:  python gen_vectors.py [--n 256] [--scenario ...] [--self-check]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from scripts.export_for_c import ADC_HEADROOM
from simulator.beat_signal_generator import FMCWBeatSignalGenerator, load_scenario

DC_VALUE = 1000
ADC_BITS = 12
ALIGN_SHIFT = 3
CODE_MAX = (1 << (ADC_BITS - 1)) - 1      # 2047
CODE_MIN = -(1 << (ADC_BITS - 1))         # -2048
SCENARIO = "scenarios/scenario_mimo.json"
OUT = Path(__file__).resolve().parent / "vectors.h"


def quantize(x: np.ndarray, full_scale: float) -> np.ndarray:
    """One component onto the 12-bit grid, then left-aligned into int16.

    Rounding is half away from zero, matching C's lround, not NumPy's
    half-to-even. The clip test is written against the rounding boundary so
    the decision happens before the rounding, as it does in C.
    """
    r = x * ((1 << (ADC_BITS - 1)) / full_scale)
    q = np.trunc(r + np.copysign(0.5, r))
    q = np.clip(q, CODE_MIN, CODE_MAX)
    return (q.astype(np.int32) << ALIGN_SHIFT).astype(np.int16)


def radar_vector(scenario: str, n: int) -> np.ndarray:
    cfg, targets = load_scenario(str(ROOT / scenario))
    gen = FMCWBeatSignalGenerator(cfg)
    frame = gen.generate_frame_mimo(targets, frame_index=0)
    seg = np.asarray(frame[0, 0, :n])
    if len(seg) != n:
        raise SystemExit(f"scenario has {len(seg)} samples per chirp, wanted {n}")
    peak = max(float(np.max(np.abs(seg.real))), float(np.max(np.abs(seg.imag))))
    full_scale = peak * ADC_HEADROOM if peak > 0.0 else 1.0
    out = np.empty(n, dtype=[("re", np.int16), ("im", np.int16)])
    out["re"] = quantize(seg.real, full_scale)
    out["im"] = quantize(seg.imag, full_scale)
    return out


def fmt(name: str, v: np.ndarray) -> str:
    rows = ",\n".join(
        "    {%6d, %6d}" % (int(s["re"]), int(s["im"])) for s in v)
    return f"static const vec_sample VEC_ATTR {name}[VEC_N] = {{\n{rows}\n}};\n"


def render(radar: np.ndarray, dc: np.ndarray, scenario: str, n: int) -> str:
    return f"""/* Generated by gen_vectors.py from {scenario} — do not edit.
 *
 * Flash and RAM are separate address spaces on AVR, so there these tables
 * are marked PROGMEM and read through accessors. On every other target the
 * attribute is empty and the accessors are plain indexing; a const table
 * lands in flash on Cortex-M by the linker script alone.
 */
#ifndef VECTORS_H
#define VECTORS_H
#include <stdint.h>

#ifdef __AVR__
#include <avr/pgmspace.h>
#define VEC_ATTR PROGMEM
#define VEC_RE(v, i) ((int16_t)pgm_read_word(&(v)[i].re))
#define VEC_IM(v, i) ((int16_t)pgm_read_word(&(v)[i].im))
#else
#define VEC_ATTR
#define VEC_RE(v, i) ((v)[i].re)
#define VEC_IM(v, i) ((v)[i].im)
#endif

#define VEC_N {n}

typedef struct {{ int16_t re, im; }} vec_sample;

{fmt("vec_dc", dc)}
{fmt("vec_radar", radar)}
#endif
"""


def self_check(radar: np.ndarray, dc: np.ndarray, n: int) -> None:
    """Properties that must hold, checkable without a reference transform.

    Every quantized value is a multiple of 8, because it is a 12-bit code
    shifted left by 3 — the sharpest available evidence that the alignment
    was applied exactly once.
    """
    assert len(radar) == n and len(dc) == n, "wrong vector length"
    assert n & (n - 1) == 0 and n >= 2, "n must be a power of two"
    for f in ("re", "im"):
        assert np.all(radar[f] % 8 == 0), f"radar {f} not left-aligned by 3"
        lim = CODE_MAX << ALIGN_SHIFT
        assert np.all(np.abs(radar[f].astype(np.int32)) <= lim), \
            f"radar {f} outside the 12-bit grid"
    assert np.all(dc["re"] == DC_VALUE) and np.all(dc["im"] == 0), "dc corrupt"
    assert np.any(radar["re"] != 0), "radar vector is all zero"
    print(f"self-check passed: {n} samples, "
          f"peak |re| {int(np.max(np.abs(radar['re'])))}, "
          f"peak |im| {int(np.max(np.abs(radar['im'])))}")


def main() -> None:
    ap = argparse.ArgumentParser(description="Emit vectors.h for the Nucleo harness.")
    ap.add_argument("--n", type=int, default=256, help="transform length")
    ap.add_argument("--scenario", default=SCENARIO)
    ap.add_argument("--self-check", action="store_true")
    args = ap.parse_args()

    radar = radar_vector(args.scenario, args.n)
    dc = np.zeros(args.n, dtype=[("re", np.int16), ("im", np.int16)])
    dc["re"] = DC_VALUE

    if args.self_check:
        self_check(radar, dc, args.n)
    OUT.write_text(render(radar, dc, args.scenario, args.n))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
